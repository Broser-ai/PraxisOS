#!/usr/bin/env bash
# Generate git-truth stub for Claude Code ↔ Cursor full export.
# Does NOT replace human/agent fill of session-trace, verify, NEXT.
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel 2>/dev/null || true)"
if [[ -z "${ROOT}" ]]; then
  echo "error: not inside a git repository" >&2
  exit 1
fi
cd "${ROOT}"

OUT="${1:-docs/exports/LATEST.md}"
BASE="${AGENT_EXPORT_BASE:-main}"
DIRECTION="${AGENT_EXPORT_DIRECTION:-Claude Code → Cursor Cloud}"
AUTHOR="${AGENT_EXPORT_AUTHOR:-Claude Code}"
SLUG="${AGENT_EXPORT_SLUG:-}"

mkdir -p "$(dirname "${OUT}")"

BRANCH="$(git rev-parse --abbrev-ref HEAD)"
SHA="$(git rev-parse HEAD)"
UTC="$(date -u +"%Y-%m-%dT%H:%M:%SZ")"
DIRTY="no"
if [[ -n "$(git status --porcelain)" ]]; then
  DIRTY="yes"
fi

REMOTE_URL_RAW="$(git remote get-url origin 2>/dev/null || echo "unknown")"
# Never embed tokens/credentials from remote URLs into exports.
REMOTE_URL="$(
  printf '%s\n' "${REMOTE_URL_RAW}" | sed -E \
    -e 's#https://[^@/]+@#https://#' \
    -e 's#http://[^@/]+@#http://#' \
    -e 's#git://[^@/]+@#git://#'
)"
LOG="$(git log --oneline "${BASE}..HEAD" 2>/dev/null | head -40 || echo "(no commits vs ${BASE}, or base missing)")"
STAT="$(git diff --stat "${BASE}...HEAD" 2>/dev/null || echo "(diff unavailable)")"
STATUS="$(git status --short)"

PR_URL=""
if command -v gh >/dev/null 2>&1; then
  PR_URL="$(gh pr view --json url -q .url 2>/dev/null || true)"
fi

cat > "${OUT}" <<EOF
